#!/usr/bin/env python3
"""Write RULES.md, a readable table of the 21 rules, from the registered library (frozen_tree/genes/genes.it1.jsonl).

    python quickstart/make_rules_table.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "frozen_tree", "genes", "genes.it1.jsonl")
WHEN = {"pre_exec": "before the program runs", "post_exec": "after the program runs"}
SOURCE = {"dev_failure_derived": "failures on development problems"}


def main():
    genes = [json.loads(l) for l in open(SRC, encoding="utf-8") if l.strip() and not l.startswith("#")]
    genes.sort(key=lambda g: (-int(g["preference"].get("priority", 0)), g["geneId"]))
    out = ["# The 21 rules", "",
           "Generated by `quickstart/make_rules_table.py` from the registered library "
           "`frozen_tree/genes/genes.it1.jsonl`, in the order the checks run (highest priority first). "
           "The full record of a rule also holds its contract text, its repair instruction, its version history "
           "and the development problems it came from.", "",
           "The gene-repair condition of the article uses the rules whose last column says *gene repair*; "
           "the others are used only by the condition that asks for a written specification before the program.", "",
           "| # | Rule | What it asks | Why | Checked | Used by |", "|---|---|---|---|---|---|"]
    for n, g in enumerate(genes, 1):
        v, p = g["validation"], g["preference"]
        when = WHEN.get(v.get("phase", "pre_exec"), v.get("phase"))
        if v.get("severity") == "soft":
            when += " (warning only)"
        conds = g["scope"].get("conditions") or []
        used = "gene repair" if "C3L" in conds else "specification condition"
        cell = lambda s: " ".join(str(s).split()).replace("|", "\\|")  # noqa: E731
        out.append(f"| {n} | `{g['geneId'].replace('orgene.', '')}` v{g['version']} | {cell(p['statement'])} | "
                   f"{cell(p.get('rationale', ''))} | {when} | {used} |")
    open(os.path.join(ROOT, "RULES.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"wrote RULES.md ({len(genes)} rules)")


if __name__ == "__main__":
    main()
